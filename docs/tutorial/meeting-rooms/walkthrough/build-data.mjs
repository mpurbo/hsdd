#!/usr/bin/env node
// Regenerates data.js: the repository under ../execute/ as it stood after
// each stage of the run, read from git history, so the walkthrough's file
// viewer shows each file as that stage left it. Zero dependencies.
//
// Usage (from anywhere inside the repository):
//   node docs/tutorial/meeting-rooms/walkthrough/build-data.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const top = execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd: here, encoding: "utf8" }).trim();
const git = (args, input) =>
  execFileSync("git", args, { cwd: top, input, maxBuffer: 512 * 1024 * 1024 });
const EXECUTE = "docs/tutorial/meeting-rooms/execute/";

// The commit that closes each stage of the run (see process-log.md).
const STAGES = JSON.parse(readFileSync(join(here, "stages.json"), "utf8"));

// A file larger than this keeps its first MAX_BYTES (cut at a line end) and
// a closing line that says how much is left out. The run's decision ledger
// (about 475 KB at the end) is the file this cap is for: each step's own
// decisions are in its sidecar, hsdd/auto/steps/S{n}.decisions.jsonl.
const MAX_BYTES = 100_000;

// Read every blob the stages name in one `git cat-file --batch` call.
function readBlobs(ids) {
  const out = git(["cat-file", "--batch"], ids.join("\n") + "\n");
  const blobs = new Map();
  let at = 0;
  for (const id of ids) {
    const eol = out.indexOf(0x0a, at);
    const [sha, , size] = out.subarray(at, eol).toString("utf8").split(" ");
    const start = eol + 1, end = start + Number(size);
    blobs.set(sha, out.subarray(start, end));
    at = end + 1;
  }
  return blobs;
}

function asText(buf) {
  if (buf.subarray(0, 8000).includes(0)) return `(binary file, ${buf.length} bytes; not embedded here)`;
  if (buf.length <= MAX_BYTES) return buf.toString("utf8");
  const cut = buf.lastIndexOf(0x0a, MAX_BYTES);
  const head = buf.subarray(0, cut > 0 ? cut : MAX_BYTES).toString("utf8");
  return `${head}\n(${buf.length} bytes in all; the first ${cut > 0 ? cut : MAX_BYTES} are embedded here. Open the file in the repository for the rest.)\n`;
}

const listed = {};
for (const [id, ref] of Object.entries(STAGES)) {
  const sha = git(["rev-parse", "--short", ref]).toString().trim();
  const rows = git(["ls-tree", "-r", sha, "--", EXECUTE]).toString().split("\n").filter(Boolean);
  listed[id] = { sha, rows: rows.map((r) => { const [meta, full] = r.split("\t"); return [full.slice(EXECUTE.length), meta.split(" ")[2]]; }) };
}
const ids = [...new Set(Object.values(listed).flatMap((s) => s.rows.map(([, b]) => b)))];
const raw = readBlobs(ids);

const blobs = [];
const blobIndex = new Map();
const stages = {};
for (const [id, { sha, rows }] of Object.entries(listed)) {
  stages[id] = {
    sha,
    files: rows.map(([path, b]) => {
      if (!blobIndex.has(b)) { blobIndex.set(b, blobs.length); blobs.push(asText(raw.get(b))); }
      return [path, blobIndex.get(b)];
    }),
  };
}

const log = readFileSync(join(here, "process-log.md"), "utf8");
// The run's own files hold a few em dashes (a skill template, the prose
// rules that ban them) and quote the banned phrase those rules name. Both are
// written as JSON escapes, so data.js itself holds neither and the browser
// still shows each file as it is.
const json = JSON.stringify({ stages, blobs, log })
  .replace(/\u2014/g, "\\u2014")
  .replace(/(load)-(bearing)/gi, "$1\\u002d$2");
const out = `// Generated by build-data.mjs from git history. Do not edit by hand.
window.WALK_DATA = ${json};
`;
writeFileSync(join(here, "data.js"), out);
console.log(`data.js: ${Object.keys(stages).length} stages, ${blobs.length} distinct file versions, ${(out.length / 1024).toFixed(0)} KiB (repo ${top})`);
