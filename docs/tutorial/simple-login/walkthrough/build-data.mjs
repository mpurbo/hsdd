#!/usr/bin/env node
// Regenerates data.js: the repository under ../execute/ as it stood after
// each stage of the run, read from git history, so the walkthrough's file
// viewer shows each file as that stage left it. Zero dependencies.
//
// Usage (from anywhere inside the repository):
//   node docs/tutorial/simple-login/walkthrough/build-data.mjs
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const top = execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd: here, encoding: "utf8" }).trim();
const git = (...args) => execFileSync("git", args, { cwd: top, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const EXECUTE = "docs/tutorial/simple-login/execute/";

// The commit that closes each stage of the run (see process-log.md).
const STAGES = JSON.parse(readFileSync(join(here, "stages.json"), "utf8"));

const MAX_BYTES = 120_000;
const blobs = [];
const blobIndex = new Map();
const stages = {};

for (const [id, ref] of Object.entries(STAGES)) {
  const sha = git("rev-parse", "--short", ref).trim();
  const paths = git("ls-tree", "-r", "--name-only", sha, "--", EXECUTE).split("\n").filter(Boolean);
  const files = [];
  for (const full of paths) {
    const rel = full.slice(EXECUTE.length);
    let text = git("show", `${sha}:${full}`);
    if (text.length > MAX_BYTES) text = `(${text.length} bytes; open the file in the repository)`;
    const hash = createHash("sha1").update(text).digest("hex");
    if (!blobIndex.has(hash)) { blobIndex.set(hash, blobs.length); blobs.push(text); }
    files.push([rel, blobIndex.get(hash)]);
  }
  stages[id] = { sha, files };
}

const log = readFileSync(join(here, "process-log.md"), "utf8");
const out = `// Generated by build-data.mjs from git history. Do not edit by hand.
window.WALK_DATA = ${JSON.stringify({ stages, blobs, log })};
`;
writeFileSync(join(here, "data.js"), out);
console.log(`data.js: ${Object.keys(stages).length} stages, ${blobs.length} distinct file versions, ${(out.length / 1024).toFixed(0)} KiB (repo ${top})`);
